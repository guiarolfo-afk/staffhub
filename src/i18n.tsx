const DICTS: Record<Lang, Dict> = { es, pt, en };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
  ta: (k: string) => string[];
}

const Ctx = createContext<I18nCtx>({
  lang: "es",
  setLang: () => undefined,
  t: (k) => k,
  ta: (k) => [k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("sh360-lang");
      if (saved === "es" || saved === "pt" || saved === "en") return saved;
    } catch {
      /* noop */
    }
    return "es";
  });

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("sh360-lang", l);
    } catch {
      /* noop */
    }
  }, []);

  const t = useCallback(
    (k: string) => {
      const v = DICTS[lang][k] ?? DICTS.es[k] ?? k;
      return Array.isArray(v) ? v.join(" · ") : v;
    },
    [lang],
  );

  const ta = useCallback(
    (k: string) => {
      const v = DICTS[lang][k] ?? DICTS.es[k] ?? [k];
      return Array.isArray(v) ? v : [v];
    },
    [lang],
  );

  return <Ctx.Provider value={{ lang, setLang, t, ta }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
